export const HSK_LEVELS = [1, 2, 3, 4, 5];

const LETTERS = 'ABCDEFGHIJ';

// Danh sách lựa chọn của một câu: [{ code, text }].
export function hskChoices(group, question) {
  const texts = question.options || group.bank || [];
  return texts.map((text, index) => ({ code: group.codes?.[index] || LETTERS[index], text }));
}

export function hskQuestions(test) {
  return test.parts.flatMap((part) => part.groups.flatMap((group) => group.questions.map((question) => ({ ...question, group, part }))));
}

// Điểm thang 100, làm tròn. Đạt khi >= HSK_PASS_SCORE.
export function scoreHsk(test, answers) {
  const questions = hskQuestions(test);
  const correct = questions.filter((question) => answers[`q${question.n}`] === question.answer).length;
  const score = Math.round((correct / questions.length) * 100);
  return { correct, total: questions.length, score, passed: score >= HSK_PASS_SCORE };
}
